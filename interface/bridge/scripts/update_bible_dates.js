for (const matiere of matieres) {
  const nom = matiere.nom;
  if (!bible[nom]) continue;

  const b = bible[nom];

  // CM
  if (b.cm) {
    for (const [titre, date] of Object.entries(b.cm)) {
      db.prepare('UPDATE cours_cm SET dateCM = ? WHERE matiere_id = ? AND titre = ?')
        .run(date, matiere.id, titre);
    }
  }

  // TD
  if (b.td) {
    for (const [titre, date] of Object.entries(b.td)) {
      db.prepare('UPDATE exercices SET datePrevue = ? WHERE matiere_id = ? AND titre = ? AND type = ?')
        .run(date, matiere.id, titre, 'TD');
    }
  }

  // TP
  if (b.tp) {
    for (const [titre, date] of Object.entries(b.tp)) {
      db.prepare('UPDATE exercices SET dateTP = ? WHERE matiere_id = ? AND titre = ? AND type = ?')
        .run(date, matiere.id, titre, 'TP');
    }
  }
}

